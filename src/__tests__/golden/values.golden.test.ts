/** Fixtures that are no factories of a value: each fakes the browser, or serves fetch. */
const NOT_VALUES = new Set(['fakeDevice', 'fakeFullscreen', 'serveNotes'])

/** Sets and maps as their entries, in order; regular expressions and functions by name. */
const plain = (value: unknown): unknown => {
  if (value instanceof Set) return [...value].map(each => plain(each))
  if (value instanceof Map) return [...value].map(each => plain(each))
  if (value instanceof RegExp) return String(value)
  if (typeof value === 'function') return `[function ${value.name}]`
  if (Array.isArray(value)) return value.map(each => plain(each))
  if (value instanceof Date || typeof value !== 'object' || value === null) {
    return value
  }
  return Object.fromEntries(
    Object.entries(value).map(([key, each]) => [key, plain(each)]),
  )
}

/** What a fixture makes, or why it's skipped. */
const made = (name: string, fixture: unknown) => {
  if (typeof fixture !== 'function') return { value: plain(fixture) }
  if (NOT_VALUES.has(name)) return { skipped: 'not a value' }
  try {
    return { value: plain((fixture as () => unknown)()) }
  } catch {
    return { skipped: 'needs arguments' }
  }
}

/** Math.random as a fixed sequence (an LCG, seed 43), for any fixture that throws dice. */
const lcg = () => {
  let seed = 43
  return () => {
    seed = (1_664_525 * seed + 1_013_904_223) % 2 ** 32
    return seed / 2 ** 32
  }
}

beforeEach(() => {
  jest.useFakeTimers({ now: new Date('2026-10-04T19:30:00.000Z') })
  jest.spyOn(Math, 'random').mockImplementation(lcg())
})

afterEach(() => {
  jest.useRealTimers()
})

