// The v0.43 metrics: `node metrics.mjs <eslint.json> <metrics.md> <ratchet.json> <commit> [label]`.
// The eslint JSON is `eslint . -f json` on the commit; everything else is read from the tree.
import fs from 'node:fs'
import { barrels, cycles, importGraph } from './graph.mjs'
import { isTest, sourceFiles, table } from './lib.mjs'
import { complexity, ratchet, readLint, syntaxCheck } from './lint.mjs'
import { disables, namedTypes, sizes, tsxExports } from './source.mjs'

const [eslintJson, mdOut, ratchetOut, commit, label = 'base'] = process.argv.slice(2)
if (!ratchetOut || !commit) {
  console.error('usage: node metrics.mjs <eslint.json> <metrics.md> <ratchet.json> <commit>')
  process.exit(2)
}

const lint = readLint(eslintJson)
const files = sourceFiles()
const lintedFiles = lint.map(r => r.file).filter(f => /\.(ts|tsx|js|jsx|mjs|cjs)$/.test(f))
const sum = values => values.reduce((a, b) => a + b, 0)
const out = []
const say = (...lines) => out.push(...lines, '')
const headlines = []

// 1. Warnings per rule and folder (the ratchet).
const r = ratchet(lint)
const RATCHET_NOTE =
  'Warnings per unit (src/features/<feature>, else the top-level folder) per rule; a unit or ' +
  'rule that is missing has 0. ' +
  'Gate 9: no count may rise.'
fs.writeFileSync(
  ratchetOut,
  `${JSON.stringify({ commit, label, command: 'eslint . -f json', note: RATCHET_NOTE, ...r }, undefined, 2)}\n`,
)
const folders = Object.keys(r.byFolder)
const rules = [...new Set(folders.flatMap(f => Object.keys(r.byFolder[f])))].sort()
const ruleTotal = rule => sum(folders.map(f => r.byFolder[f][rule] ?? 0))
rules.sort((a, b) => ruleTotal(b) - ruleTotal(a) || a.localeCompare(b))

say(
  `# v0.43 metrics: ${label} (${commit})`,
  `Generated by .refactor/analysis/metrics/metrics.mjs from \`eslint . -f json\` on ${commit} ` +
    'and the tree at that commit. The ratchet (gate 9) is ratchet-base.json, then ' +
    'ratchet-moved.json from commit 5: warnings per unit (src/features/<feature>, else the ' +
    'top-level folder) per rule (no-restricted-syntax also split by check); no count may rise.',
)
const HEADLINES_AT = out.length
headlines.push(
  `Lint: ${r.totals.files} files, ${r.totals.errors} errors, ${r.totals.warnings} warnings.`,
)

say('## 1. Warnings per rule and folder')
say(
  table(
    ['rule', 'total', ...folders],
    rules.map(rule => [
      rule,
      ruleTotal(rule),
      ...folders.map(f => r.byFolder[f][rule] ?? ''),
    ]),
  ),
)
const checks = [...new Set(folders.flatMap(f => Object.keys(r.noRestrictedSyntaxByCheck[f] ?? {})))]
const checkTotal = check => sum(folders.map(f => r.noRestrictedSyntaxByCheck[f]?.[check] ?? 0))
say(
  'no-restricted-syntax by check (one-export, hook-export, utility-export, type-export: rule ' +
    '(a); tsx-type, ts-type-export: rule (b)):',
)
say(
  table(
    ['check', 'total', ...folders],
    checks
      .sort((a, b) => checkTotal(b) - checkTotal(a))
      .map(check => [
        check,
        checkTotal(check),
        ...folders.map(f => r.noRestrictedSyntaxByCheck[f]?.[check] ?? ''),
      ]),
  ),
)

// 2. .tsx files breaking rule (a).
const breaking = tsxExports(files)
const lintA = new Set(
  lint
    .filter(({ messages }) =>
      messages.some(
        m =>
          m.ruleId === 'no-restricted-syntax' &&
          syntaxCheck(m.message).endsWith('-export') &&
          syntaxCheck(m.message) !== 'ts-type-export',
      ),
    )
    .map(({ file }) => file),
)
const mineA = new Set(breaking.map(b => b.file))
const multiExport = breaking.filter(b => b.exported.filter(e => e.kind !== 'framework').length > 1)
const tsxCount = files.filter(f => f.endsWith('.tsx')).length
const productTsx = files.filter(f => f.endsWith('.tsx') && !isTest(f)).length
say(
  '## 2. .tsx files breaking rule (a): one export, a component, nothing else',
  `${breaking.length} of ${tsxCount} .tsx files (${breaking.filter(b => !isTest(b.file)).length} ` +
    `of ${productTsx} outside tests); ` +
    `${multiExport.length} export ` +
    'more than one thing. Kinds: component (PascalCase), hook (use*), utility (any other value ' +
    'name), type, star (`export *`), default (unnamed), framework (a route file’s Next.js name).',
  `Lint agrees on ${[...mineA].filter(f => lintA.has(f)).length} files; only this list: ` +
    `${[...mineA].filter(f => !lintA.has(f)).join(', ') || 'none'}; only lint: ` +
    `${[...lintA].filter(f => !mineA.has(f)).join(', ') || 'none'}.`,
)
headlines.push(
  `Rule (a): ${breaking.length} of ${tsxCount} .tsx files break it (${breaking.filter(b => !isTest(b.file)).length} ` +
    `of ${productTsx} outside tests); ${multiExport.length} export more than one thing.`,
)
say(
  table(
    ['file', 'exports', 'what they are'],
    breaking.map(({ file, exported }) => [
      file,
      exported.length,
      exported.map(e => `${e.name} (${e.kind})`).join(', '),
    ]),
  ),
)

// 3. Named types.
const { inTsx, exportedTs, isTypesHome } = namedTypes(files)
const flaggedTs = [...exportedTs].filter(([file]) => !isTypesHome(file))
const homeTs = [...exportedTs].filter(([file]) => isTypesHome(file))
const total = entries => sum([...entries].map(([, n]) => n))
const testTsx = [...inTsx].filter(([file]) => isTest(file))
say(
  '## 3. Named types: in .tsx files, and exported outside types.ts',
  `In .tsx files: ${total([...inTsx])} type aliases and interfaces in ${inTsx.size} files ` +
    `(${total(testTsx)} of them in ${testTsx.length} test files).`,
  `Exported from .ts files other than types.ts: ${total(exportedTs)} in ${exportedTs.size} ` +
    `files; of them ${total(homeTs)} in ${homeTs.length} files under src/types/ (exempt in ` +
    `commit 1's config, CLAUDE.md §4's application-wide types) and ${total(flaggedTs)} in ` +
    `${flaggedTs.length} files elsewhere (the ts-type-export warnings).`,
)
headlines.push(
  `Rule (b): ${total([...inTsx])} named types in ${inTsx.size} .tsx files (${total([...inTsx]) - total(testTsx)} ` +
    `in ${inTsx.size - testTsx.length} outside tests); ${total(flaggedTs)} exported named types in ` +
    `${flaggedTs.length} .ts files outside types.ts and src/types/ (${total(homeTs)} more in src/types/).`,
)
const byCount = map => [...map].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
say('### Named types in .tsx files')
say(table(['file', 'types'], byCount(inTsx)))
say('### Exported named types in .ts files outside types.ts')
say(
  table(
    ['file', 'types', 'exempt (src/types/)'],
    byCount(exportedTs).map(([file, n]) => [file, n, isTypesHome(file) ? 'yes' : '']),
  ),
)

// 4. Cognitive complexity over 15.
const complex = complexity(lint)
say(
  '## 4. Functions over cognitive complexity 15 (sonarjs)',
  `${complex.length} functions (${complex.filter(c => !isTest(c.file)).length} outside tests). ` +
    'sonarjs adds a nested function’s complexity to the function around it and reports the ' +
    'outer one, so callbacks inside a component count toward the component.',
)
headlines.push(
  `Cognitive complexity over 15: ${complex.length} functions; the top five: ` +
    `${complex.slice(0, 5).map(c => `${c.name} ${c.score}`).join(', ')}.`,
)
say(
  table(
    ['score', 'file:line', 'function'],
    complex.map(c => [c.score, `${c.file}:${c.line}`, c.name]),
  ),
)

// 5. Import cycles.
const graph = importGraph(files)
const groups = cycles(graph)
const lintCycleFiles = new Set(
  lint.filter(l => l.messages.some(m => m.ruleId === 'import/no-cycle')).map(l => l.file),
)
const runtimeCount = groups.filter(g => g.runtimeGroups.length > 0).length
say(
  '## 5. Import cycles',
  `${graph.pairs.length} import edges between src files (${graph.pairs.filter(p => p.type).length} ` +
    `type-only, ${graph.pairs.filter(p => p.dynamic).length} dynamic). ${groups.length} cyclic ` +
    `groups (strongly connected components) counting type-only imports; ${runtimeCount} ` +
    'with a runtime cycle. import/no-cycle warns in ' +
    `${lintCycleFiles.size} files: ${[...lintCycleFiles].sort().join(', ') || 'none'}.`,
)
headlines.push(
  `Import cycles: ${groups.length} cyclic groups counting type-only imports, ${runtimeCount} ` +
    `runtime (${groups.filter(g => g.runtimeGroups.length > 0).map(g => g.files.length + ' files in ' + g.folders.join(', ')).join('; ')}); ` +
    `${groups.filter(g => g.folders.length > 1).length} span folders.`,
)
for (const [n, g] of groups.entries()) {
  say(
    `### Group ${n + 1}: ${g.files.length} files, ${g.runtimeGroups.length > 0 ? 'runtime' : 'type-only'}` +
      `, ${g.folders.length > 1 ? `across ${g.folders.length} folders` : 'one folder'}`,
    `Files: ${g.files.join(', ')}.`,
    ...g.runtimeGroups.map(rg => `Runtime cycle among: ${rg.join(', ')}.`),
    'Edges inside the group:',
  )
  say(
    table(
      ['from', 'to', 'import'],
      g.edges.map(e => [e.from, e.to, e.type ? 'type-only' : e.dynamic ? 'dynamic' : 'runtime']),
    ),
  )
  say(
    `Elementary cycles (${g.cycles.length}${g.cycles.length >= 50 ? ', capped at 50' : ''}):`,
    ...g.cycles.map(c => `- ${c.type ? 'type-only' : 'runtime'}: ${[...c.files, c.files[0]].join(' → ')}`),
  )
}

// 6. Barrels.
const barrelRows = barrels(graph, files)
say(
  '## 6. Barrel files (index.ts)',
  `${barrelRows.length} barrels, imported by ${sum(barrelRows.map(b => b.importers))} files in all.`,
)
headlines.push(
  `Barrels: ${barrelRows.length} index.ts files, ${sum(barrelRows.map(b => b.importers))} importing files.`,
)
say(table(['barrel', 'importers'], barrelRows.map(b => [b.file, b.importers])))

// 7. eslint-disable comments.
const disableRows = disables(lintedFiles)
const byRule = new Map()
for (const row of disableRows) {
  if (!byRule.has(row.rule)) byRule.set(row.rule, [])
  byRule.get(row.rule).push(row)
}
const countBy = (rows, test) => rows.filter(test).length
const commentLines = new Set(disableRows.map(d => `${d.file}:${d.line}`))
const wholeFile = disableRows.filter(d => d.scope === 'file')
const broad = disableRows.filter(d => d.scope === 'file' || d.scope === 'range')
say(
  '## 7. eslint-disable inventory',
  `${commentLines.size} directive comments naming ${disableRows.length} rule entries ` +
    `(${countBy(disableRows, d => d.test)} in tests). By scope: ` +
    `${countBy(disableRows, d => d.scope === 'line')} line, ${countBy(disableRows, d => d.scope === 'range')} ` +
    `range, ${wholeFile.length} whole-file (in ${new Set(wholeFile.map(d => d.file)).size} files). ` +
    `With an ESLint \`-- reason\`: ${countBy(disableRows, d => d.reason === '-- reason')}; a comment ` +
    `just above instead: ${countBy(disableRows, d => d.reason === 'comment above')}; none: ` +
    `${countBy(disableRows, d => d.reason === 'none')}.`,
)
headlines.push(
  `eslint-disable: ${commentLines.size} comments, ${wholeFile.length} whole-file and ` +
    `${countBy(disableRows, d => d.scope === 'range')} range; ` +
    `${countBy(disableRows, d => d.reason === 'none')} with no reason (and ` +
    `${countBy(disableRows, d => d.reason === 'comment above')} with only a comment above); ` +
    `${[...byRule].sort((a, b) => b[1].length - a[1].length).slice(0, 2).map(([rule, rows]) => `${rule} ${rows.length}`).join(', ')}.`,
)
say(
  table(
    ['rule', 'entries', 'line', 'range', 'whole-file', '-- reason', 'comment above', 'none'],
    [...byRule]
      .sort((a, b) => b[1].length - a[1].length)
      .map(([rule, rows]) => [
        rule,
        rows.length,
        countBy(rows, d => d.scope === 'line'),
        countBy(rows, d => d.scope === 'range'),
        countBy(rows, d => d.scope === 'file'),
        countBy(rows, d => d.reason === '-- reason'),
        countBy(rows, d => d.reason === 'comment above'),
        countBy(rows, d => d.reason === 'none'),
      ]),
  ),
)
const noReason = disableRows.filter(d => d.reason === 'none')
say('### Entries with no reason')
say(table(['file:line', 'rule', 'scope'], noReason.map(d => [`${d.file}:${d.line}`, d.rule, d.scope])))
say('### Whole-file and range disables')
say(
  table(
    ['file:line', 'rule', 'scope', 'reason'],
    broad.map(d => [`${d.file}:${d.line}`, d.rule, d.scope, d.reason]),
  ),
)

// 8. Sizes.
const big = sizes(files, 500)
say(
  '## 8. Files over 500 lines',
  `${big.length} files (${big.filter(b => !b.test).length} outside tests).`,
)
headlines.push(
  `Files over 500 lines: ${big.length} (${big.filter(b => !b.test).length} outside tests; largest ` +
    `outside tests: ${big.filter(b => !b.test).slice(0, 3).map(b => `${b.file} ${b.lines}`).join(', ')}).`,
)
say(table(['lines', 'file', 'test'], big.map(b => [b.lines, b.file, b.test ? 'yes' : ''])))

out.splice(HEADLINES_AT, 0, '## Headlines', '', ...headlines.map(h => `- ${h}`), '')
fs.writeFileSync(mdOut, `${out.join('\n').trimEnd()}\n`)
